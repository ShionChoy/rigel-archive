import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { defineConfig } from 'astro/config';
import cloudflare from '@astrojs/cloudflare';
import ts from 'typescript';

/**
 * `astro dev` runs the processing container in Docker, as it runs when deployed. Where there is no Docker
 * (a cloud sandbox, Docker Desktop not started), dev would refuse to start: it runs instead from a copy of
 * wrangler.jsonc with the container turned off. The site works as usual; uploads are then processed by
 * `uv run ra worker --site http://localhost:4321`.
 */
function devConfigPath() {
  if (!process.argv.includes('dev')) return undefined;
  try {
    execFileSync('docker', ['info'], { stdio: 'ignore', timeout: 10_000 });
    return undefined;
  } catch {
    const { config, error } = ts.parseConfigFileTextToJson('wrangler.jsonc', readFileSync('wrangler.jsonc', 'utf8'));
    if (error) throw new Error(`wrangler.jsonc: ${ts.flattenDiagnosticMessageText(error.messageText, '\n')}`);
    config.dev = { ...config.dev, enable_containers: false };
    const path = 'wrangler.dev-no-container.jsonc';
    writeFileSync(path, `// Generated by astro.config.mjs from wrangler.jsonc because Docker is not available.\n${JSON.stringify(config, null, 2)}\n`);
    console.warn(`Docker 不可用：本次开发不启动处理容器（改用 ${path}）；上传由 uv run ra worker --site http://localhost:4321 处理。`);
    return path;
  }
}

export default defineConfig({
  output: 'server',
  adapter: cloudflare({ imageService: 'passthrough', configPath: devConfigPath() }),
  // Admin auth comes from Cloudflare Access, not Astro sessions, so no KV binding is needed.
  session: false,
  security: { checkOrigin: true },
});
